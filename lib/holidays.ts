// 노동절·선거일에 철도 운영사가 휴일 시간표를 쓰는지는 확인하지 못했다.
// 휴일 막차가 평일보다 이르므로, 모르는 날은 휴일로 보는 쪽이 안전하다.

const HOLIDAYS: Record<number, string[]> = {
  // 2026년 자료는 2024년에 만들어져 노동절(5/1)이 빠져 있었다. 지난 날짜라 계산에는 영향 없다
  2026: [
    '01-01', '02-16', '02-17', '02-18', '03-01', '03-02', '05-01', '05-05', '05-24', '05-25',
    '06-03', '06-06', '07-17', '08-15', '08-17', '09-24', '09-25', '09-26', '10-03', '10-05',
    '10-09', '12-25',
  ],
  2027: [
    '01-01', '02-06', '02-07', '02-08', '02-09', '03-01', '05-01', '05-03', '05-05', '05-13',
    '06-06', '07-17', '07-19', '08-15', '08-16', '09-14', '09-15', '09-16', '10-03', '10-04',
    '10-09', '10-11', '12-25', '12-27',
  ],
  2028: [
    '01-01', '01-26', '01-27', '01-28', '03-01', '04-12', '05-01', '05-02', '05-05', '06-06',
    '07-17', '08-15', '10-02', '10-03', '10-04', '10-05', '10-09', '12-25',
  ],
};

const SET = new Set(Object.entries(HOLIDAYS).flatMap(([y, days]) => days.map((d) => `${y}-${d}`)));

/** 달력 날짜(현지 시각)가 공휴일인지. 운행일 기준으로 쓰려면 serviceDay()를 넘긴다 */
export function isHoliday(date: Date): boolean {
  const pad = (n: number) => String(n).padStart(2, '0');
  return SET.has(`${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`);
}
